inline constexpr const ExplorerFrameProfile* FindExplorerFrameProfile(
    std::int64_t fileSize, std::uint32_t timestamp, std::uint32_t imageSize) noexcept {
    for (const auto& profile : ExplorerFrameProfiles) {
        if (profile.fileSize == fileSize && profile.timestamp == timestamp && profile.imageSize == imageSize)
            return &profile;
    }
    return nullptr;
}
